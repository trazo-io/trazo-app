/**
 * The activity screens say "activity" and "season", in both languages (2026-11-07).
 *
 * The season screens were renamed in app #318. The screens one step further in still said
 * production / event: the parcel page's button reads "Log activity" and the tour pointing at
 * it said "Tap Add event"; the activity form told a farmer with no season underway to "Start a
 * production"; the detail modal deleted an "Event"; the Documents filer asked which
 * "production" a receipt belongs to. This reads every message key these screens reference and
 * checks the words, so a new string on them is checked without being listed here.
 */
import { readFileSync } from 'fs';
import { join, resolve } from 'path';
import { describe, expect, it } from 'vitest';

const SRC = resolve(__dirname, '../../../../../..');
const en: Record<string, string> = JSON.parse(
  readFileSync(join(SRC, 'i18n/lang/en-US.json'), 'utf8')
);
const es: Record<string, string> = JSON.parse(
  readFileSync(join(SRC, 'i18n/lang/es-419.json'), 'utf8')
);

const FORMS = 'views/Dashboard/Dashboard/components/forms/';
const SCREENS = [
  `${FORMS}NewEvent.jsx`,
  `${FORMS}BusinessTab-SIMPLIFIED.jsx`,
  `${FORMS}ChemicalTab-ENHANCED.jsx`,
  `${FORMS}CrewNoteRows.jsx`,
  `${FORMS}CustomFieldsForm.tsx`,
  `${FORMS}GeneralTab.jsx`,
  `${FORMS}PestManagementTab.jsx`,
  `${FORMS}ProductionTab.jsx`,
  `${FORMS}SoilManagementTab.jsx`,
  `${FORMS}WeatherTab.jsx`,
  'components/Events/ActivityReview.tsx',
  'components/Events/ApplicationGroupNotice.tsx',
  'components/Events/CarbonImpactPreview.tsx',
  'components/Events/EventPreviewModal.tsx',
  'components/Events/MultiParcel.tsx',
  'components/Events/ParcelPicker.tsx',
  'components/Events/RegistryFieldRenderer.tsx',
  'components/Events/VoiceEventCapture.tsx',
  'components/Modals/EventDetailsModal.tsx',
  'views/Dashboard/Activities/index.tsx',
  'views/Dashboard/Activities/ActivityDetailModal.tsx',
  'tours/parcelTour.ts',
  'tours/documentsTour.ts',
  'views/Dashboard/Documents/index.tsx',
  'components/PURExport/PURExportModal.tsx',
  'components/AuditExport/AuditExportModal.tsx',
  'views/Dashboard/Dashboard/Farm/OperationAuditExportButton.tsx'
];

// Where the word is the right one. Each entry says why.
const NOP = '"organic production" / "production" is the regulation\'s own word (7 CFR 205.2)';
const WEATHER =
  'a frost or heat EVENT is the weather itself, not the record; the verb is "Weather event"';
const KEEP: Record<string, string> = {
  'production.field.productionMethod':
    'organic / transitional / conventional is the production METHOD (7 CFR 205)',
  'events.chemical.form.organicBasisHelp': NOP,
  'events.chemical.organicBasis.required': NOP,
  'events.chemical.massBalance.body': '§ 205.103(b)(2) quoted: "through production, to sale"',
  'events.production.help.cleaningMaterials': NOP,
  'events.production.help.cleaningSection': NOP,
  'events.weather.fields.weatherEventType': WEATHER,
  'events.weather.help.autoGeneratedFromWeatherTypeCustomizeForSpec': WEATHER,
  'events.weather.help.minimumTemperatureRecordedDuringFrostEvent': WEATHER,
  'events.weather.help.peakTemperatureDuringHeatEvent': WEATHER,
  'events.weather.placeholders.optionalDescribeHowThisWeatherEventAffectedY': WEATHER,
  'events.weather.placeholders.selectWeatherEventType': WEATHER,
  'events.weather.validation.typeRequired': WEATHER,
  'activities.verb.weather': WEATHER
};

const EN_WORDS = /\b(productions?|events?)\b/i;
const ES_WORDS = /\b(producci(ó|o)n|producciones|eventos?)\b/i;

const read = (file: string) => readFileSync(join(SRC, file), 'utf8');
const keysOn = (file: string) =>
  [...read(file).matchAll(/['"`]([a-zA-Z]+(?:\.[a-zA-Z0-9_]+)+)['"`]/g)]
    .map((m) => m[1])
    .filter((k) => k in en);

describe('activity screens say activity and season', () => {
  it.each(SCREENS)('%s', (file) => {
    const keys = keysOn(file);
    expect(keys.length, 'read no message keys: this would pass vacuously').toBeGreaterThan(0);
    const wrong = keys
      .filter((k) => !(k in KEEP))
      .flatMap((k) => [
        ...(EN_WORDS.test(en[k]) ? [`en ${k}: ${en[k]}`] : []),
        ...(es[k] && ES_WORDS.test(es[k]) ? [`es ${k}: ${es[k]}`] : [])
      ]);
    expect(wrong).toEqual([]);
  });

  it.each(SCREENS)('%s has no hardcoded English that says event or production', (file) => {
    // A literal never reaches a Spanish farmer in Spanish, and a word sweep over the locale
    // files cannot see it. JSX props and `|| 'fallback'` are where these lived.
    const code = read(file);
    const props = [
      ...code.matchAll(/\b(description|helpText|title|label|placeholder)="([^"]*)"/g)
    ].filter((m) => EN_WORDS.test(m[2]));
    const fallbacks = [...code.matchAll(/\|\|\s*\n?\s*'([^']*)'/g)].filter((m) =>
      EN_WORDS.test(m[1])
    );
    expect([...props, ...fallbacks].map((m) => m[0])).toEqual([]);
  });

  it.each(SCREENS)('%s: every validation message is a key in both locales', (file) => {
    // A zod schema at module scope cannot call intl, so its message is a KEY and the field
    // renders it through intl. Any literal here reaches a Spanish farmer in English, whatever
    // its words (review of app #321 caught "Activity type is required" on the General tab).
    // `req(path, message)` in the summary-mode refinements is not rendered by any field, so it
    // is not checked here.
    const code = read(file);
    const messages = [
      ...code.matchAll(/\.(?:min|max)\(\d+, '([^']+)'\)|\bmessage: '([^']+)'/g)
    ].map((m) => m[1] || m[2]);
    const literal = messages.filter((id) => !(id in en) || !(id in es));
    expect(literal).toEqual([]);
  });

  it('a field that shows a key-valued error renders it through intl', () => {
    // The other half of the rule: a key handed straight to `error=` prints the key itself.
    for (const file of SCREENS.filter((f) => f.startsWith(FORMS))) {
      const code = read(file);
      const keyed = [...code.matchAll(/(\w+): string\(\)[^\n]*\.min\(1, '([a-z]+\.[^']+)'\)/g)]
        .map((m) => m[1])
        .concat([...code.matchAll(/path: \['(\w+)'\],[^}]*message: '[a-z]+\./g)].map((m) => m[1]));
      for (const field of keyed) {
        expect(code, `${file}: errors.${field} shown without intl`).not.toMatch(
          new RegExp(`error=\\{\\s*[\\w.]*errors\\.${field}\\?\\.message\\s*\\}`)
        );
      }
    }
  });

  it('the parcel tour names what the parcel page shows', () => {
    for (const lang of [en, es]) {
      expect(lang['tour.parcel.step1.title']).toBe(lang['parcelPage.currentSeason']);
      expect(lang['tour.parcel.step3.title']).toBe(lang['parcelPage.logActivity']);
      expect(lang['tour.parcel.step4.title']).toBe(lang['parcelPage.seasons']);
      expect(lang['tour.parcel.step3.content']).toContain(lang['parcelPage.logActivity']);
    }
  });

  it('the activity form asks for a season the way the parcel page does', () => {
    for (const lang of [en, es]) {
      expect(lang['events.noOpenSeason.startCta']).toBe(lang['parcelPage.startSeason']);
      expect(lang['events.noOpenSeason.title']).toBe(lang['parcelPage.noSeasonUnderway']);
    }
  });

  it('the category chip on an activity row and its detail modal does not say production', () => {
    // `eventTypeAppearance` builds the key at runtime (`activities.type.${code}`), so the
    // per-screen scan above cannot see it. Type 1 said "Production" until 2026-11-07.
    const types = Object.keys(en).filter((k) => /^activities\.type\.\d$/.test(k));
    expect(types.length).toBeGreaterThanOrEqual(7);
    for (const k of types) {
      expect(en[k], k).not.toMatch(EN_WORDS);
      expect(es[k], k).not.toMatch(ES_WORDS);
    }
  });

  it('every reason the carbon preview gives for "no emissions" exists in both locales', () => {
    const code = read('components/Events/CarbonImpactPreview.tsx');
    const block = code.slice(
      code.indexOf('const transparencyReason'),
      code.indexOf('const transparencyMessage')
    );
    const reasons = [...block.matchAll(/'([a-z]+)'/g)].map((m) => m[1]);
    expect(reasons.length).toBe(7);
    for (const r of reasons) {
      expect(en[`carbonPreview.noEmissions.${r}`], r).toBeTruthy();
      expect(es[`carbonPreview.noEmissions.${r}`], r).toBeTruthy();
    }
  });
});
